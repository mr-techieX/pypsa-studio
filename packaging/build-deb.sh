#!/usr/bin/env bash
set -euo pipefail

# Build on a Linux filesystem using Ubuntu/Debian Python and dpkg-deb.
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VERSION="$(PYTHONPATH="$ROOT" python3 -c 'from energy_gui import __version__; print(__version__)')"
ARCH="$(dpkg --print-architecture)"
PACKAGE="pypsa-studio"
WORK="$(mktemp -d "${TMPDIR:-/tmp}/pypsa-studio-deb.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
STAGE="$WORK/stage"
OUTPUT="${OUTPUT_DIR:-$ROOT/dist}"
APP="$STAGE/opt/pypsa-studio"

mkdir -p "$APP/app" "$APP/python" "$STAGE/usr/bin" \
    "$STAGE/usr/share/applications" "$STAGE/usr/share/doc/$PACKAGE" \
    "$STAGE/usr/share/icons/hicolor/scalable/apps" \
    "$STAGE/opt/Attribute-Info" "$OUTPUT"

# Keep generated bytecode, user projects, test fixtures, and the Windows venv out.
tar -C "$ROOT" --exclude='./EnEx' --exclude='./tests' --exclude='./myTest' \
    --exclude='./dist' --exclude='./packaging' --exclude='__pycache__' \
    --exclude='*.pyc' --exclude='./.pytest_cache' \
    -cf - energy_gui | tar -C "$APP/app" -xf -

# The in-app F1 reference resolver is intentionally relative to /opt/Attribute-Info.
tar -C "$ROOT/../../Attribute-Info" -cf - . | tar -C "$STAGE/opt/Attribute-Info" -xf -

# Vendored pure-Python/native wheel dependencies make install independent of pip.
# Runtime still uses Ubuntu's Python ABI, so build on the target Ubuntu release.
if python3 -m pip --version >/dev/null 2>&1; then
    PIP=(python3 -m pip)
else
    # Ubuntu may omit pip from its system Python. Bootstrap only inside this
    # temporary build directory; do not modify the distro Python installation.
    curl -fL --retry 2 https://bootstrap.pypa.io/pip/pip.pyz -o "$WORK/pip.pyz"
    PIP=(python3 "$WORK/pip.pyz")
fi
"${PIP[@]}" install --disable-pip-version-check --no-compile \
    --target "$APP/python" -r "$ROOT/requirements.txt"

cat > "$STAGE/usr/bin/pypsa-studio" <<'EOF'
#!/bin/sh
set -eu
APP=/opt/pypsa-studio
export PYTHONPATH="$APP/app:$APP/python${PYTHONPATH:+:$PYTHONPATH}"
exec /usr/bin/python3 -m energy_gui "$@"
EOF
chmod 0755 "$STAGE/usr/bin/pypsa-studio"

cat > "$STAGE/usr/share/applications/pypsa-studio.desktop" <<'EOF'
[Desktop Entry]
Type=Application
Name=PyPSA Studio
Comment=Local energy-system modeling and analysis workbench
Exec=pypsa-studio
Icon=pypsa-studio
Terminal=false
Categories=Science;Engineering;
StartupNotify=true
EOF

install -m 0644 "$ROOT/energy_gui/assets/pypsa-studio.svg" \
    "$STAGE/usr/share/icons/hicolor/scalable/apps/pypsa-studio.svg"

install -m 0644 "$ROOT/README.md" "$STAGE/usr/share/doc/$PACKAGE/README.md"
install -m 0644 "$ROOT/THIRD_PARTY_NOTICES.md" "$STAGE/usr/share/doc/$PACKAGE/THIRD_PARTY_NOTICES.md"

mkdir -p "$STAGE/DEBIAN"
cat > "$STAGE/DEBIAN/control" <<EOF
Package: $PACKAGE
Version: $VERSION-1
Section: science
Priority: optional
Architecture: $ARCH
Depends: python3 (>= 3.12), libgl1, libegl1, libopengl0, libxkbcommon-x11-0, libxcb-cursor0, libxcb-icccm4, libxcb-keysyms1, libxcb-shape0, libxcb-xinerama0, libxcb-xkb1, libx11-xcb1, libdbus-1-3, libfontconfig1, libfreetype6
Maintainer: Local Energy Workbench <noreply@localhost>
Description: Local PyPSA energy-system modeling workbench
 Development build for WSLg/Linux desktop use. Installs the application and
 pinned Python dependencies under /opt/pypsa-studio; user data stays in the
 user's selected project folders and Qt application-data directory.
EOF

ARTIFACT="$WORK/${PACKAGE}_${VERSION}-1_${ARCH}.deb"
dpkg-deb --root-owner-group --build "$STAGE" "$ARTIFACT"
install -m 0644 "$ARTIFACT" "$OUTPUT/$(basename "$ARTIFACT")"
echo "Built: $OUTPUT/$(basename "$ARTIFACT")"
